import { AlertTriangle, CheckCircle2, FileSearch } from "lucide-react";
import SectionLabel from "./SectionLabel";
import type { EvidenceType } from "../types";
import styles from "./AnalysisPanel.module.css";

export type AnalysisState =
  | { kind: "empty" }
  | { kind: "rejected"; message: string }
  | {
      kind: "accepted";
      caseRef: string;
      openedAt: string;
      evidenceType: EvidenceType;
      evidenceSummary: string;
    };

const PLANNED_OUTPUT = [
  "Classification of the message or screenshot by fraud type",
  "Suspicious phrases with numbered margin notes",
  "Extracted identifiers: phone numbers, UPI IDs, URLs, account numbers",
  "Recommended actions and reporting routes",
];

interface AnalysisPanelProps {
  state: AnalysisState;
}

export default function AnalysisPanel({ state }: AnalysisPanelProps) {
  if (state.kind === "empty") {
    return (
      <section className={styles.section} aria-live="polite">
        <SectionLabel aside="Awaiting evidence">Analysis</SectionLabel>
        <div className={styles.empty}>
          <FileSearch size={18} aria-hidden="true" className={styles.emptyIcon} />
          <p className={styles.emptyTitle}>No analysis recorded for this session.</p>
          <p className={styles.emptyText}>
            Results will be filed here once evidence is submitted and the analysis
            service is connected. Nothing is pre-filled and no risk score is
            generated by the interface itself.
          </p>
        </div>
      </section>
    );
  }

  if (state.kind === "rejected") {
    return (
      <section className={styles.section} aria-live="assertive">
        <SectionLabel aside="Not submitted">Analysis</SectionLabel>
        <div className={styles.rejected}>
          <AlertTriangle size={16} aria-hidden="true" className={styles.rejectedIcon} />
          <div>
            <p className={styles.rejectedTitle}>Evidence was not accepted</p>
            <p className={styles.rejectedText}>{state.message}</p>
          </div>
        </div>
      </section>
    );
  }

  return (
    <section className={styles.section} aria-live="polite">
      <SectionLabel aside={state.caseRef}>Analysis</SectionLabel>

      <article className={styles.panel}>
        <header className={styles.panelHeader}>
          <span className={styles.stamp}>
            <CheckCircle2 size={13} aria-hidden="true" />
            Case logged
          </span>
          <dl className={styles.metaList}>
            <div className={styles.metaRow}>
              <dt>Case reference</dt>
              <dd className="mono">{state.caseRef}</dd>
            </div>
            <div className={styles.metaRow}>
              <dt>Opened</dt>
              <dd className="mono">{state.openedAt}</dd>
            </div>
            <div className={styles.metaRow}>
              <dt>Evidence type</dt>
              <dd className="mono">
                {state.evidenceType === "message" ? "Message text" : "Screenshot"}
              </dd>
            </div>
            <div className={styles.metaRow}>
              <dt>Received</dt>
              <dd className="mono">{state.evidenceSummary}</dd>
            </div>
          </dl>
        </header>

        <hr className="rule" />

        <div className={styles.body}>
          <h3 className={styles.noticeTitle}>Analysis engine not yet connected.</h3>
          <p className={styles.noticeText}>
            The evidence you supplied has been recorded against the case reference
            above. No classification, risk score, or recommended action has been
            produced — the analysis service is implemented in the next phase, and
            this interface will not invent one in the meantime.
          </p>

          <h4 className={styles.plannedLabel}>Will be filed in Phase 2</h4>
          <ol className={styles.plannedList}>
            {PLANNED_OUTPUT.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ol>
        </div>
      </article>
    </section>
  );
}
